"""Text-to-SQL inference with a QLoRA fine-tuned Gemma 4 E2B LiteRT-LM model.

Auto-detects local cache (matching the pattern in EmbeddingGemma2_LiteRT_RAG.py):
  - If the `.litertlm` file is already cached locally, loads it offline.
  - If not, automatically downloads it from Hugging Face Hub on the first run.
  - Also supports passing a local `.litertlm` file directly via `--model-path`.

Usage:
  uv run python apps/qlora_gemma_4_e2b_LiteRT.py --repo-id <hf-user>/gemma-text-to-sql-litertlm
  uv run python apps/qlora_gemma_4_e2b_LiteRT.py --model-path /path/to/model.litertlm
  uv run python apps/qlora_gemma_4_e2b_LiteRT.py --repo-id <hf-user>/gemma-text-to-sql-litertlm \\
      --schema "CREATE TABLE users (id INT, name TEXT);" \\
      --query "List all user names."
"""

import argparse
import os
import time
from pathlib import Path

import litert_lm
from huggingface_hub import hf_hub_download

# Low-spec CPU settings (matching EmbeddingGemma2_LiteRT_RAG.py)
NUM_THREADS = 4
MAX_NUM_TOKENS = 1024
DEFAULT_REPO_ID = "shogoorg/gemma-text-to-sql-litertlm"
DEFAULT_FILENAME = "model.litertlm"

SYSTEM_MESSAGE = (
    "You are a text to SQL query translator. "
    "Users will ask you questions in English and you will generate a SQL query "
    "based on the provided SCHEMA."
)

USER_PROMPT_TEMPLATE = """Given the <USER_QUERY> and the <SCHEMA>, generate the corresponding SQL command to retrieve the desired data, considering the query's syntax, semantics, and schema constraints.

<SCHEMA>
{schema}
</SCHEMA>

<USER_QUERY>
{question}
</USER_QUERY>"""

SAMPLE_QUERIES = [
    (
        "CREATE TABLE users (id INT, name TEXT, country TEXT);",
        "List all user names from Japan.",
    ),
    (
        (
            "CREATE TABLE sales (id INT, product TEXT, amount DECIMAL, sale_date DATE);\n"
            "CREATE TABLE products (name TEXT, category TEXT);"
        ),
        "What is the total sales amount per product category in 2026?",
    ),
]

litert_lm.set_min_log_severity(litert_lm.LogSeverity.ERROR)


def resolve_repo_id(repo_id: str | None) -> str:
    """Resolve the Hugging Face repo ID from CLI arg, env var, or default."""
    if repo_id:
        return repo_id
    return os.environ.get("HF_REPO_ID", DEFAULT_REPO_ID)


def load_hf_model_file(repo_id: str, filename: str) -> str:
    """Load model from local cache if present, otherwise download online."""
    try:
        path = hf_hub_download(
            repo_id=repo_id, filename=filename, local_files_only=True
        )
        print(f"Loaded from cache: {filename}")
        return path
    except Exception:
        print(f"Downloading {filename} from Hugging Face ({repo_id})...")
        return hf_hub_download(
            repo_id=repo_id, filename=filename, local_files_only=False
        )


def build_cpu_backend(num_threads: int):
    """Build a LiteRT-LM CPU backend compatible with both callable and enum APIs."""
    cpu_attr = getattr(litert_lm.Backend, "CPU", None)
    if callable(cpu_attr):
        return cpu_attr(thread_count=num_threads)
    return litert_lm.Backend.CPU


def system_messages() -> list[litert_lm.Message]:
    return [litert_lm.Message.system(SYSTEM_MESSAGE)]


def generate_sql_stream(
    engine: litert_lm.Engine, schema: str, question: str
):
    """Stream a SQL query generated by the LiteRT-LM engine."""
    prompt = USER_PROMPT_TEMPLATE.format(schema=schema, question=question)
    with engine.create_conversation(
        messages=system_messages(),
        sampler_config=litert_lm.SamplerConfig(top_k=1),
    ) as conversation:
        if hasattr(conversation, "send_message_async"):
            for chunk in conversation.send_message_async(prompt):
                if isinstance(chunk, dict):
                    for item in chunk.get("content", []):
                        if isinstance(item, dict) and item.get("text"):
                            yield item["text"]
                else:
                    yield str(chunk)
        else:
            reply = conversation.send_message(prompt)
            if isinstance(reply, dict):
                for item in reply.get("content", []):
                    if isinstance(item, dict) and item.get("text"):
                        yield item["text"]
            else:
                yield str(reply)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Download and run Text-to-SQL inference with a Gemma 4 E2B .litertlm model."
    )
    parser.add_argument(
        "--repo-id",
        default=None,
        help="Hugging Face repo ID (e.g. <user>/gemma-text-to-sql-litertlm). Defaults to HF_REPO_ID or <whoami>/gemma-text-to-sql-litertlm.",
    )
    parser.add_argument(
        "--filename",
        default=DEFAULT_FILENAME,
        help=f"Model filename in the Hugging Face repo (default: {DEFAULT_FILENAME}).",
    )
    parser.add_argument(
        "--model-path",
        default=None,
        help="Optional local path to an existing .litertlm file (skips Hugging Face download).",
    )
    parser.add_argument(
        "--schema",
        default=None,
        help="Custom SQL schema string (use together with --query).",
    )
    parser.add_argument(
        "--query",
        default=None,
        help="Custom natural-language question (use together with --schema).",
    )
    parser.add_argument(
        "--threads",
        type=int,
        default=NUM_THREADS,
        help=f"Number of CPU threads (default: {NUM_THREADS}).",
    )
    parser.add_argument(
        "--max-num-tokens",
        type=int,
        default=MAX_NUM_TOKENS,
        help=f"Maximum context tokens (default: {MAX_NUM_TOKENS}).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    if args.model_path:
        model_file = Path(args.model_path)
        if not model_file.is_file():
            raise FileNotFoundError(f"Local model file not found: {model_file}")
        model_path = str(model_file)
        print(f"Using local model: {model_path}")
    else:
        repo_id = resolve_repo_id(args.repo_id)
        model_path = load_hf_model_file(repo_id=repo_id, filename=args.filename)

    print(f"Generation model: {model_path}")
    print("=" * 60)

    print("Loading LiteRT-LM engine (CPU backend)...")
    engine = litert_lm.Engine(
        model_path,
        backend=build_cpu_backend(args.threads),
        max_num_tokens=args.max_num_tokens,
    )
    print("=" * 60)

    if args.schema and args.query:
        queries = [(args.schema, args.query)]
    else:
        queries = SAMPLE_QUERIES

    try:
        for i, (schema, question) in enumerate(queries, start=1):
            print(f"[{i}] Schema:\n{schema}")
            print(f"[{i}] Query: {question}")
            print("SQL:")
            start = time.perf_counter()
            for text in generate_sql_stream(engine, schema, question):
                print(text, end="", flush=True)
            elapsed_ms = (time.perf_counter() - start) * 1000
            print(f"\n({elapsed_ms:.0f} ms)")
            print("-" * 60)
    finally:
        engine.close()


if __name__ == "__main__":
    main()
